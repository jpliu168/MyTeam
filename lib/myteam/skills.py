"""Render shared skills + each member's role instructions into the member's
workspace, in every format agents read:

  .claude/skills/<name>/SKILL.md   (Claude Code, native)
  AGENTS.md                        (Codex, Antigravity, most other CLIs)

Sources: MyTeam/skills/* (common pool, shared by everyone) and the member's
role template instructions (roles.py, or the custom text on the role card).
Placeholders: {{MEMBER}} {{ROLE}} {{FOCUS}} {{GROUP}} {{STATE}}
"""
import re

from . import config, packs, roles

MARK = "<!-- generated by `myteam skills sync` — edit MyTeam/skills/ or the role card instead -->"


def _render(text, cfg, m):
    subs = {
        "{{MEMBER}}": config.display(m),
        "{{MEMBER_ID}}": m["name"],
        "{{ROLE}}": m.get("role_title") or m["role"],
        "{{FOCUS}}": m.get("focus") or "(not specified)",
        "{{GROUP}}": cfg["group"],
        "{{STATE}}": str(config.STATE),
        "{{BOSS}}": packs.of(cfg)["boss"],
        "{{UNIT}}": packs.of(cfg)["unit"],
    }
    for k, v in subs.items():
        text = text.replace(k, v)
    return text


def _split_frontmatter(text):
    mm = re.match(r"^---\n(.*?)\n---\n(.*)$", text, re.S)
    if mm:
        return mm.group(1), mm.group(2).lstrip("\n")
    return "", text


def _role_skill(m, cfg=None):
    tpl = roles.by_id(m["role"], packs.of(cfg)["id"])
    body = m.get("instructions") or (tpl["instructions"] if tpl else "")
    title = m.get("role_title") or (tpl["title"] if tpl else m["role"])
    return (
        "---\nname: my-role\ndescription: {member}'s role in {{{{GROUP}}}} — read "
        "this to know your job. Always applies.\n---\n\n"
        "# Your role: {title}\n\n"
        "You are **{display}**{idnote}, a member of **{{{{GROUP}}}}**. "
        "Focus: {{{{FOCUS}}}}.\n\n{body}\n{folders}".format(
            folders=_folders_section(m),
            member=config.display(m), display=config.display(m), title=title, body=body,
            idnote="" if config.display(m).lower() == m["name"] else
            " (team id `{}` — use it in myteam commands)".format(m["name"]))
    )


def _folders_section(m):
    lines = ["", "## Your folders", "",
             "- **Working folder (home):** `{}` — keep your own notes and drafts here.".format(
                 config.member_dir(m["name"])),
             "- **Shared team folders:** `{0}/deliverables/` (finished work for the owner), "
             "`{0}/handbook/`, `{0}/bus/`.".format(config.STATE)]
    extra = config.member_folders(m)
    if extra:
        lines.append("- **Extra folders the owner gave you:**")
        lines += ["  - `{}`".format(f) for f in extra]
    lines += ["", "Read and write only in these folders. If a task needs a folder "
              "that isn't listed, ask the owner to add it in setup — don't go elsewhere.", ""]
    return "\n".join(lines)


def sources(cfg):
    """(render-name, source-dir) for the shared skills of this team's preset."""
    src = config.root() / "skills"
    out = []
    for name, d in packs.of(cfg)["skills"].items():
        f = src / d / "SKILL.md"
        if f.exists():
            out.append((name, f))
    return out


def sync(cfg):
    import json
    import shutil
    from . import profile
    shared = sources(cfg)
    prof_name = profile.title(cfg)[0]
    for m in cfg["members"]:
        mdir = config.member_dir(m["name"])
        agents_md = ["# AGENTS.md — {} ({}) @ {}".format(
            config.display(m), m.get("role_title") or m["role"], cfg["group"]), MARK, ""]
        all_sources = [("my-role", _role_skill(m, cfg)),
                       (prof_name, profile.skill_text(cfg))] + \
                      [(n, f.read_text()) for n, f in shared]
        sdir = mdir / ".claude" / "skills"
        manifest = sdir / ".myteam-generated.json"
        try:
            before = set(json.loads(manifest.read_text()))
        except (OSError, ValueError):
            before = set()
        now = set()
        for sname, raw in all_sources:
            rendered = _render(raw, cfg, m)
            dest = sdir / sname
            dest.mkdir(parents=True, exist_ok=True)
            (dest / "SKILL.md").write_text(rendered)
            now.add(sname)
            _, body = _split_frontmatter(rendered)
            agents_md += ["---", "", body.strip(), ""]
        legacy = {t[0] for t in profile.TITLE.values()} - now   # old profile skills
        for stale in (before - now) | {x for x in legacy if (sdir / x).exists()}:
            shutil.rmtree(sdir / stale, ignore_errors=True)
        manifest.write_text(json.dumps(sorted(now)))
        (mdir / "AGENTS.md").write_text("\n".join(agents_md) + "\n")
    if profile.filled(cfg) or (config.STATE / "handbook" / (prof_name + ".md")).exists():
        profile.write_handbook(cfg)
    return len(shared) + 2
